import type { IconSources } from './collections'

/**
 * Sources of the declarations that type icon names. One file per collection keeps each one
 * small and lets TypeScript reuse the unchanged ones; the union of `IconName` is the keys of one
 * interface, which TypeScript checks by lookup, not by comparing each member.
 */

const header = '// Generated by @meekojs/icon. Do not edit.\n'

function augmentation(interfaceName: string, keys: readonly string[]): string {
	return `${header}export {}\ndeclare module '@meekojs/icon' {\n\tinterface ${interfaceName} {\n${keys.map((key) => `\t\t${JSON.stringify(key)}: true`).join('\n')}\n\t}\n}\n`
}

/** File name of the declaration of a collection, as `addTypeTemplate` accepts it. */
export function collectionDeclarationFile(prefix: string): string {
	return `names-${prefix}.d.ts`
}

/** Every declaration the module writes: the names of each collection, the local icons and the installed collections. */
export function iconDeclarations(sources: IconSources, installed: readonly string[]): Map<string, string> {
	const files = new Map<string, string>()
	for (const collection of sources.collections.values())
		files.set(
			collectionDeclarationFile(collection.prefix),
			augmentation(
				'GeneratedIconNames',
				collection.names.map((name) => `${collection.prefix}:${name}`),
			),
		)
	if (sources.locals.size) files.set('names-local.d.ts', augmentation('GeneratedIconNames', [...sources.locals.keys()].sort()))
	files.set('collections.d.ts', augmentation('GeneratedIconCollections', [...new Set([...installed, ...sources.collections.keys()])].sort()))
	return files
}
