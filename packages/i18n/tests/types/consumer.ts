import type { I18n, I18nMessageValues, I18nValue } from "@meekojs/i18n";

declare module "@meekojs/i18n" {
  interface GeneratedI18nMessages {
    welcome: { readonly name: I18nValue };
    items: { readonly total: number; readonly owner: I18nValue };
    ready: {};
    legacy: true;
  }
}

declare const i18n: I18n;
i18n.t("welcome", { name: "Meeko" });
i18n.t("items", { total: 2, owner: "Diego" });
i18n.t("ready");
i18n.t("ready", {});
i18n.t("legacy");
const values: I18nMessageValues<"items"> = { total: 1, owner: "Team" };
i18n.t("items", values);
declare const dynamic: "welcome" | "ready";
i18n.t(dynamic, { name: "Team" });
// @ts-expect-error A dynamic key can require parameters, even when another alternative is static.
i18n.t(dynamic);
declare const requiredUnion: "welcome" | "items";
i18n.t(requiredUnion, { name: "Team", owner: "Team", total: 2 });
// @ts-expect-error Values must satisfy every possible dynamic message contract.
i18n.t(requiredUnion, { name: "Team" });
// @ts-expect-error A message key is checked against the generated registry.
i18n.t("missing");
// @ts-expect-error Required interpolation values cannot be omitted.
i18n.t("welcome");
// @ts-expect-error All named placeholders are required.
i18n.t("welcome", {});
// @ts-expect-error Null cannot fill a required placeholder.
i18n.t("welcome", { name: null });
// @ts-expect-error Plural selectors require numbers.
i18n.t("items", { total: "two", owner: "Team" });
// @ts-expect-error The count alias is generated by the runtime and does not replace total.
i18n.t("items", { count: 2, owner: "Team" });
// @ts-expect-error Static messages do not declare placeholder values.
i18n.t("ready", { extra: true });
