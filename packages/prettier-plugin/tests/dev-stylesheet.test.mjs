import corePlugin from '@meekojs/meeko/prettier'
import assert from 'node:assert/strict'
import { mkdir, mkdtemp, rm, utimes, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import test, { after, before } from 'node:test'
import { format } from 'prettier'

import plugin from '../dist/index.js'

// `meekoSortClasses: "stylesheet"` orders by `.meeko/styles/main.css`, the stylesheet that `meeko dev`
// writes after the whole Vite pipeline, when it exists; otherwise by `app/styles/main.css` processed here.
const devSheet = '.meeko/styles/main.css'
const devCss = (...classes) => `/* Generated by meeko dev */\n@layer theme, utilities;\n${classes.map((name) => `.${name.replaceAll(':', '\\:')} { color: red; }`).join('\n')}\n`
const component = '<template>\n<div class="hover:underline  p-4 extra flex alpha zeta p-4">x</div>\n</template>\n'
const classOf = (formatted) => /<div class="([^"]*)">/.exec(formatted)[1]
const now = Math.floor(Date.now() / 1000)

const warnings = []
const write = process.stderr.write
before(() => {
	process.stderr.write = (chunk, ...rest) => {
		if (typeof chunk === 'string' && chunk.startsWith('[meeko] Aviso:')) warnings.push(chunk)
		else write.call(process.stderr, chunk, ...rest)
		return true
	}
})
after(() => {
	process.stderr.write = write
})

const roots = []
after(async () => {
	await Promise.all(roots.map((root) => rm(root, { recursive: true, force: true })))
})

async function project(files) {
	const root = await mkdtemp(join(tmpdir(), 'meeko-dev-stylesheet-'))
	roots.push(root)
	for (const [path, contents] of Object.entries({ 'meeko.config.ts': 'export default {}\n', ...files })) {
		await mkdir(dirname(join(root, path)), { recursive: true })
		await writeFile(join(root, path), contents)
	}
	return root
}

const dated = (root, path, seconds) => utimes(join(root, path), seconds, seconds)
// Each copy of the formatter (this package and the core) warns once; both say the same.
const own = (root) => [...new Set(warnings.filter((warning) => warning.includes(root)))]

/** The plugin of this package and the one of the core give the same, stable text. */
async function sorted(root, source = component) {
	const options = { filepath: join(root, 'app', 'components', 'Box.meeko'), meekoSortClasses: 'stylesheet' }
	const text = await format(source, { ...options, plugins: [plugin] })
	assert.equal(await format(source, { ...options, plugins: [corePlugin] }), text, 'the core gives the same')
	assert.equal(await format(text, { ...options, plugins: [plugin] }), text, 'stable')
	return classOf(text)
}

test('orders by the stylesheet of meeko dev, which holds what the processing of the project does not, and follows its changes', async () => {
	const root = await project({ 'app/styles/main.css': '.zeta { color: red; }\n.alpha { color: blue; }\n', [devSheet]: devCss('flex', 'p-4', 'zeta', 'hover:underline') })
	await dated(root, devSheet, now + 10)
	// `flex`, `p-4` and `hover:underline` only exist in the stylesheet of meeko dev; `alpha` only in app/styles/main.css.
	assert.equal(await sorted(root), 'extra alpha flex p-4 zeta hover:underline')

	await writeFile(join(root, devSheet), devCss('hover:underline', 'zeta', 'p-4', 'flex'))
	await dated(root, devSheet, now + 20)
	assert.equal(await sorted(root), 'extra alpha hover:underline zeta p-4 flex')

	// Without it, the processed app/styles/main.css, where the utilities are unknown.
	await rm(join(root, devSheet))
	assert.equal(await sorted(root), 'hover:underline p-4 extra flex zeta alpha')
	await writeFile(join(root, devSheet), devCss('flex', 'p-4'))
	await dated(root, devSheet, now + 30)
	assert.equal(await sorted(root), 'hover:underline extra alpha zeta flex p-4')
	assert.deepEqual(own(root), [])
})

test('orders by the stylesheet of meeko dev without app/styles/main.css', async () => {
	const root = await project({ [devSheet]: devCss('flex', 'p-4') })
	assert.equal(await sorted(root), 'hover:underline extra alpha zeta flex p-4')
	assert.deepEqual(own(root), [])
})

test('a stylesheet of meeko dev older than app/styles/main.css still orders, and warns once', async () => {
	const root = await project({ 'app/styles/main.css': '.zeta { color: red; }\n', [devSheet]: devCss('p-4', 'flex') })
	await dated(root, devSheet, now - 100)
	await dated(root, 'app/styles/main.css', now)
	assert.equal(await sorted(root), 'hover:underline extra alpha zeta p-4 flex')
	assert.equal(await sorted(root), 'hover:underline extra alpha zeta p-4 flex')
	assert.equal(own(root).length, 1, own(root).join(''))
	assert.match(own(root)[0], /ordena con \.meeko\/styles\/main\.css en .*anterior a app\/styles\/main\.css.*meeko dev/)
})

test('a stylesheet of meeko dev that is unusable falls back to app/styles/main.css', async () => {
	const main = '.zeta { color: red; }\n.alpha { color: blue; }\n'
	const empty = await project({ 'app/styles/main.css': main, [devSheet]: '/* Generated by meeko dev */\n:root { color: red; }\n' })
	assert.equal(await sorted(empty), 'hover:underline p-4 extra flex zeta alpha')
	assert.deepEqual(own(empty), [])
	const broken = await project({ 'app/styles/main.css': main, [devSheet]: '.flex { color: red;\n' })
	assert.equal(await sorted(broken), 'hover:underline p-4 extra flex zeta alpha')
	assert.equal(own(broken).length, 1, own(broken).join(''))
	assert.match(own(broken)[0], /no pudo usar \.meeko\/styles\/main\.css en .*no es CSS válido; se procesa app\/styles\/main\.css/)
})
