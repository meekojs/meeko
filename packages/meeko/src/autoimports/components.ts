import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { discoverComponents } from "./registry.js";

/**
 * Writes the project-local loader used by the `resolveComponent` autoimport. Each import has a
 * literal specifier so Vite can split the components into chunks. The loader contains no mutable
 * request state; the module cache belongs to the JavaScript runtime and the bundler.
 */
export async function generateComponentRegistry(projectRoot: string): Promise<string> {
  const root = resolve(projectRoot);
  const output = join(root, ".meeko", "generated", "components.ts");
  const directory = dirname(output);
  const components = await discoverComponents(root);
  const names = new Map<string, string>();
  const entries: string[] = [];
  for (const entry of [...components].sort((left, right) => left.name.localeCompare(right.name))) {
    const previous = names.get(entry.name);
    if (previous && previous !== entry.file) {
      throw new Error(`Componente ${entry.name} ambiguo: ${previous}, ${entry.file}. Cambia el prefijo o el nombre de uno de ellos.`);
    }
    if (previous) continue;
    names.set(entry.name, entry.file);
    const path = relative(directory, entry.file).replaceAll("\\", "/");
    if (isAbsolute(path) || /^[A-Za-z]:/.test(path)) {
      throw new Error(`No se puede generar un import relativo para ${entry.file} desde ${directory}`);
    }
    const specifier = path.startsWith(".") ? path : `./${path}`;
    entries.push(`  ${JSON.stringify(entry.name)}: () => import(${JSON.stringify(specifier)}),`);
  }
  const source = [
    "// Generated by Meeko. Edit the component sources or meeko.config.ts instead.",
    'import type { ComponentName, ComponentOf } from "@meekojs/meeko";',
    "",
    "const loaders: { readonly [Name in ComponentName]: () => Promise<ComponentOf<Name>> } = Object.freeze({",
    ...entries,
    "});",
    "",
    "/** Load a registered component. The result is a Promise because its code is split into a lazy chunk. */",
    "export function resolveComponent<Name extends ComponentName>(name: Name): Promise<ComponentOf<Name>> {",
    "  if (!Object.hasOwn(loaders, name)) return Promise.reject(new Error(`Componente de Meeko no registrado: ${String(name)}`));",
    "  return loaders[name]();",
    "}",
    "",
  ].join("\n");
  await mkdir(directory, { recursive: true });
  let previous: string | undefined;
  try { previous = await readFile(output, "utf8"); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  if (previous !== source) await writeFile(output, source, "utf8");
  return output;
}
