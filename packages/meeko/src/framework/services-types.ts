import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative, resolve } from "node:path";
import { applyAutoImports, discoverAutoImports } from "../autoimports.js";
import { replaceModuleSpecifiers } from "../compiler/import-graph.js";
import { findRuntimeFile } from "./app-manifest.js";

/** Declaration that types `GeneratedServices` from `server/runtime.ts`, relative to `.meeko`. */
export const servicesDeclaration = "types/services.d.ts";
/** TypeScript copy of `server/runtime.ts` that the declaration reads, relative to `.meeko`. */
export const serverRuntimeCopy = "types/server-runtime.ts";

async function writeIfChanged(file: string, source: string): Promise<void> {
  try { if (await readFile(file, "utf8") === source) return; }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, source, "utf8");
}

/** The relative specifier of `to` in a module at `from`, keeping the extension `to` was written with. */
function specifier(from: string, to: string): string {
  const path = relative(dirname(from), to).replaceAll("\\", "/");
  return path.startsWith(".") ? path : `./${path}`;
}

/**
 * Writes `.meeko/types/services.d.ts`, which fills `GeneratedServices` of `@meekojs/meeko/server`
 * with the services of the default export of `server/runtime.ts`, so `context.services` is typed
 * without casts. The declaration reads a copy of the runtime with its server autoimports written as
 * imports: the programs of the editor have no autoimport globals, and without them a runtime that
 * calls an autoimported `defineServerRuntime` would type as `any`. The copy has `@ts-nocheck`, so
 * its errors are reported once, on `server/runtime.ts`, by the server project. Without a TypeScript
 * runtime (none, or a `.js` one) the declaration adds nothing and `services` stays `unknown`.
 */
export async function generateServicesTypes(projectRoot: string): Promise<string> {
  const root = resolve(projectRoot);
  const declaration = join(root, ".meeko", servicesDeclaration);
  const copy = join(root, ".meeko", serverRuntimeCopy);
  const runtime = findRuntimeFile(root);
  const typed = runtime !== undefined && [".ts", ".mts"].includes(extname(runtime));
  if (!runtime || !typed) {
    await rm(copy, { force: true });
    await writeIfChanged(declaration, "// Generated by Meeko: without server/runtime.ts in TypeScript, RequestContext.services is unknown.\nexport {};\n");
    return declaration;
  }
  const original = await readFile(runtime, "utf8");
  let code: string;
  // An autoimport that does not resolve is reported on server/runtime.ts by the server project.
  try { code = applyAutoImports(original, runtime, await discoverAutoImports(root), "server"); }
  catch { code = original; }
  const source = replaceModuleSpecifiers(code, copy, ({ value }) => value.startsWith(".") ? specifier(copy, resolve(dirname(runtime), value)) : value);
  await writeIfChanged(copy, `// @ts-nocheck\n// Generated by Meeko from ${relative(root, runtime).replaceAll("\\", "/")}: its types only; edit that file instead.\n${source}`);
  const imported = `./${relative(dirname(declaration), copy).replaceAll("\\", "/").replace(/\.ts$/, ".js")}`;
  await writeIfChanged(declaration, [
    "// Generated by Meeko from server/runtime.ts: the type of RequestContext.services.",
    'import type {} from "@meekojs/meeko/server";',
    'declare module "@meekojs/meeko/server" {',
    "  interface GeneratedServices {",
    `    readonly services: import("@meekojs/meeko/server").ServerRuntimeServices<typeof import(${JSON.stringify(imported)}) extends { readonly default: infer Runtime } ? Runtime : unknown>;`,
    "  }",
    "}",
    "export {};",
    "",
  ].join("\n"));
  return declaration;
}
