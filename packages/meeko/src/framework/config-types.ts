import { lstatSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, extname, isAbsolute, join, relative, resolve, sep } from "node:path";

import type { MeekoConfig } from "../modules/define-meeko-config";

import { classifyModuleEntry, installedModulePackageNames } from "./module-loader";

/**
 * Types of `meeko.config.ts` without imports, as `.nuxt/nuxt.d.ts` does for Nuxt: the modules
 * listed by name in `modules` augment `MeekoConfig` with their `configKey`, and
 * `.meeko/types/config.d.ts` imports them so that augmentation loads by itself. The editor reads it
 * through `.meeko/tsconfig.config.json`, which the `tsconfig.json` of `meeko init` references, and
 * `meeko check` checks the configuration with it.
 */

const header = "// Generated by Meeko from modules of meeko.config.*: the modules type their keys. Do not edit.\n";

/** Project-relative path of the declaration that loads the types of the modules. */
export const configTypesPath = ".meeko/types/config.d.ts";

/**
 * Project-relative path of the index of the declarations that modules generate with
 * `addTypeTemplate`. The configuration is checked with it too, so a module can type its options
 * with what it generates (the icon names of `icon.include`, for example).
 */
export const moduleTemplatesIndexPath = ".meeko/types/modules.d.ts";

/** Project-relative path of the TypeScript project of `meeko.config.ts` for the editor. */
export const configTsconfigPath = ".meeko/tsconfig.config.json";

/** The string entries of `modules`, also those of a `[name, options]` entry. */
function moduleStrings(config: MeekoConfig): string[] {
  const result: string[] = [];
  for (const entry of config.modules ?? []) {
    const reference = Array.isArray(entry) ? (entry as readonly unknown[])[0] : entry;
    if (typeof reference === "string") result.push(reference);
  }
  return result;
}

/** The specifier that imports `file` from `.meeko/types`, or `undefined` for a file without types. */
function fileSpecifier(typesDirectory: string, file: string): string | undefined {
  const extension = extname(file);
  if (![".ts", ".mts", ".cts"].includes(extension) || file.endsWith(".d.ts")) return undefined;
  const path = relative(typesDirectory, file).replaceAll("\\", "/");
  // Type-only imports of a TypeScript file keep working under Bundler resolution without the extension.
  const withoutExtension = extension === ".ts" ? path.slice(0, -3) : `${path.slice(0, -extension.length)}${extension === ".mts" ? ".mjs" : ".cjs"}`;
  return withoutExtension.startsWith(".") ? withoutExtension : `./${withoutExtension}`;
}

/**
 * The source of `.meeko/types/config.d.ts`: a type import of each module of `modules` named by a
 * string (a package, through its `./module` subpath when it exports one, or a TypeScript file of
 * the project), and `MeekoModuleNames` with the installed module packages and those of `modules`,
 * for the completion of their names. Nothing is executed: it reads `package.json` files.
 */
export function configTypesSource(projectRoot: string, config: MeekoConfig): string {
  const root = resolve(projectRoot);
  const typesDirectory = join(root, ".meeko", "types");
  const imports = new Set<string>();
  const names = new Set(installedModulePackageNames(root));
  for (const entry of moduleStrings(config)) {
    let target;
    try { target = classifyModuleEntry(root, entry); }
    catch { continue; }
    if (target.kind !== "module") continue;
    if (target.specifier !== undefined) {
      imports.add(target.specifier);
      names.add(entry);
    } else {
      const specifier = fileSpecifier(typesDirectory, target.file);
      if (specifier) imports.add(specifier);
    }
  }
  return [
    header.trimEnd(),
    'import type {} from "@meekojs/meeko/framework";',
    ...[...imports].map((specifier) => `import type {} from ${JSON.stringify(specifier)};`),
    'declare module "@meekojs/meeko/framework" {',
    "  interface MeekoModuleNames {",
    ...[...names].sort().map((name) => `    ${JSON.stringify(name)}: true;`),
    "  }",
    "}",
    "export {};",
    "",
  ].join("\n");
}

/** The TypeScript project of `meeko.config.ts`, as `meeko check` checks it. */
export function configTsconfigSource(): string {
  return JSON.stringify({
    compilerOptions: {
      target: "ES2022", module: "ESNext", moduleResolution: "Bundler", lib: ["ES2022", "DOM"],
      types: ["node"], strict: true, noEmit: true, skipLibCheck: true, allowImportingTsExtensions: true,
    },
    include: ["../meeko.config.ts", "../meeko.config.mts", "types/config.d.ts", "types/modules.d.ts"],
  }, null, 2) + "\n";
}

/** Writes `file` when its text changes; never through a symlink, outside the project or over a file Meeko did not write. */
function writeOwned(root: string, file: string, source: string, owned: (previous: string) => boolean): void {
  mkdirSync(dirname(file), { recursive: true });
  const location = relative(realpathSync(root), realpathSync(dirname(file)));
  if (isAbsolute(location) || location === ".." || location.startsWith(`..${sep}`)) throw new Error(`Los tipos generados salen del proyecto: ${file}`);
  let previous: string | undefined;
  try {
    if (lstatSync(file).isSymbolicLink()) throw new Error(`El archivo generado es un enlace simbólico: ${file}`);
    previous = readFileSync(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  if (previous !== undefined && !owned(previous)) throw new Error(`Meeko no generó ${file}; muévalo antes de continuar`);
  if (previous !== source) writeFileSync(file, source, "utf8");
}

/**
 * Writes `.meeko/types/config.d.ts` and `.meeko/tsconfig.config.json` for a configuration, executed
 * or read statically (only the strings of `modules` count). Returns both files.
 */
export function writeConfigTypesSync(projectRoot: string, config: MeekoConfig): string[] {
  const root = resolve(projectRoot);
  const types = join(root, ...configTypesPath.split("/"));
  const tsconfig = join(root, ...configTsconfigPath.split("/"));
  writeOwned(root, types, configTypesSource(root, config), (previous) => previous.startsWith(header));
  // .meeko/ belongs to Meeko: its tsconfig files are rewritten as the others are.
  writeOwned(root, tsconfig, configTsconfigSource(), () => true);
  return [types, tsconfig];
}
