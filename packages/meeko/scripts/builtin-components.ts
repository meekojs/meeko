/**
 * Meeko's own components written as `.meeko` (`<MeekoThemeToggle>`, `<MeekoAwait>`, `<MeekoPopover>`,
 * `<MeekoSelect>`), compiled with the package's compiler into TypeScript that `tsc` builds with the
 * rest of `src/`. `pnpm run builtins` rewrites the compiled files; `tests/builtin-components.test.ts`
 * fails when one is out of date.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";

import { builtinComponentModules, compile, linkComponentModule } from "../src/compiler.ts";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Each built-in component: its `.meeko` source and the compiled module, relative to the package. */
export const builtinComponents = [...Object.values(builtinComponentModules), linkComponentModule].map(({ source, specifier }) => ({
  source,
  output: `src/builtins/${specifier.split("/").at(-1)!}.compiled.ts`,
}));

/**
 * The compiled module of a built-in component. The filename is fixed, so the output is the same on
 * every machine, and the runtime comes from `src/internal.ts` instead of the package's own export.
 * A built-in that uses another one (`<MeekoSelect>` renders `<MeekoPopover>`) imports its compiled
 * module next to it instead of `@meekojs/meeko/builtins/…`.
 */
export function compileBuiltin(source: string, file: string, output = builtinComponents.find((component) => component.source === file)?.output): string {
  if (!output) throw new Error(`${file}: no compiled output configured`);
  const name = file.split("/").at(-1)!;
  const { code } = compile(source, `/meeko/${file}`);
  const runtime = 'import * as __meeko from "@meekojs/meeko/internal";';
  if (!code.includes(runtime)) throw new Error(`${file}: the compiled module no longer imports ${runtime}`);
  let compiled = code
    .replace("// Generated by Meeko. Edit the .meeko source instead.", `// Generated by Meeko from ${name} with \`pnpm run builtins\`. Edit ${name} instead.`)
    .replace(/(\bfrom\s+["'])(\.{1,2}\/[^"']+)(["'])/g, (_match, before: string, specifier: string, after: string) => {
      const target = posix.normalize(posix.join(posix.dirname(file), specifier));
      const relative = posix.relative(posix.dirname(output), target);
      return `${before}${relative.startsWith(".") ? relative : `./${relative}`}${after}`;
    })
    .replace(runtime, 'import * as __meeko from "../internal.js";')
    // `<MeekoLink>` builds its href with the framework's href(): the package's own module, not its export.
    .replaceAll('"@meekojs/meeko/framework"', '"../framework.js"');
  for (const { specifier } of Object.values(builtinComponentModules)) {
    const module = specifier.split("/").at(-1)!;
    compiled = compiled.replace(`from ${JSON.stringify(specifier)};`, `from ${JSON.stringify(`./${module}.compiled.js`)};`);
  }
  return compiled;
}

/** The compiled modules as they should be, by output path. */
export async function builtinOutputs(): Promise<Map<string, string>> {
  const outputs = new Map<string, string>();
  for (const { source, output } of builtinComponents) {
    outputs.set(output, compileBuiltin(await readFile(join(packageRoot, source), "utf8"), source));
  }
  return outputs;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [output, code] of await builtinOutputs()) {
    await writeFile(join(packageRoot, output), code, "utf8");
    process.stdout.write(`${output}\n`);
  }
}
