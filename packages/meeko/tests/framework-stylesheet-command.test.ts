import assert from 'node:assert/strict'
import { type ChildProcess, execFile, spawn } from 'node:child_process'
import { once } from 'node:events'
import { existsSync } from 'node:fs'
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { createServer } from 'node:net'
import { dirname, join } from 'node:path'
import test from 'node:test'
import { pathToFileURL } from 'node:url'

import { initFrameworkProject } from '../src/framework/init.ts'
import { globalStylesheetSnapshotFile } from '../src/framework/styles.ts'
import { linkRepositoryPackages, repositoryRoot, stopChild, tempProject } from './helpers/temp-project.ts'

const cli = join(repositoryRoot, 'dist', 'cli.js')

interface Run {
	readonly code: number
	readonly stdout: string
	readonly stderr: string
}

/** Runs the built CLI in `root` and resolves with its exit code and output, whatever the code. */
function meeko(root: string, args: readonly string[], env: NodeJS.ProcessEnv = {}): Promise<Run> {
	return new Promise((done) => {
		execFile(process.execPath, [cli, ...args], { cwd: root, env: { ...process.env, MEEKO_EDITOR_BRIDGE: '0', ...env }, timeout: 110_000, windowsHide: true }, (error, stdout, stderr) => {
			const code = (error as { code?: unknown } | null)?.code
			done({ code: error === null ? 0 : typeof code === 'number' ? code : 1, stdout, stderr })
		})
	})
}

async function put(root: string, file: string, source: string): Promise<void> {
	await mkdir(dirname(join(root, file)), { recursive: true })
	await writeFile(join(root, file), source)
}

async function until(condition: () => boolean | Promise<boolean>, message: () => string, timeout = 30_000): Promise<void> {
	const start = Date.now()
	while (!(await condition())) {
		if (Date.now() - start > timeout) throw new Error(message())
		await new Promise((done) => setTimeout(done, 25))
	}
}

async function freePort(): Promise<number> {
	const server = createServer()
	server.listen(0, '127.0.0.1')
	await once(server, 'listening')
	const address = server.address()
	assert.ok(address && typeof address !== 'string')
	server.close()
	await once(server, 'close')
	return address.port
}

/**
 * A module whose Vite plugin appends a rule to the application stylesheet, as a CSS tool that is a
 * Vite plugin (`@tailwindcss/vite`) does: nothing a plain PostCSS pass of the file would show. It
 * fails instead while `app/styles/broken.flag` exists.
 */
const injectModule = `import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineMeekoModule } from "@meekojs/meeko/framework";

const flag = fileURLToPath(new URL("./app/styles/broken.flag", import.meta.url));

export default defineMeekoModule({ meta: { name: "inject-css" }, setup(_options, meeko) {
  meeko.addVitePlugin({
    name: "inject-css",
    transform(code, id) {
      if (!id.split("?")[0].endsWith("app/styles/main.css")) return null;
      if (existsSync(flag)) throw new Error("injected failure");
      return code + "\\n.injected-by-plugin { color: rebeccapurple; }\\n";
    },
  });
} });
`

/** A framework project with a global stylesheet and the module above. */
async function stylesProject(context: { after(fn: () => Promise<void>): void }, cleanup?: () => unknown): Promise<string> {
	const root = await tempProject(context, 'stylesheet-command', cleanup)
	await initFrameworkProject(root)
	await linkRepositoryPackages(root, ['@meekojs/meeko', 'vite'])
	await put(root, 'inject.mjs', injectModule)
	await put(root, 'meeko.config.mjs', `export default { modules: [${JSON.stringify(pathToFileURL(join(root, 'inject.mjs')).href)}] };\n`)
	await rm(join(root, 'meeko.config.ts'), { force: true })
	await put(root, 'app/styles/main.css', '@import "./tokens.css";\n.app-rule { color: red; }\n')
	await put(root, 'app/styles/tokens.css', '.token-rule { color: blue; }\n')
	return root
}

test('meeko styles writes the processed global stylesheet without a server', { timeout: 120_000 }, async (context) => {
	// The server stops before the project is removed: Windows cannot delete the working directory of a live process.
	let child: ChildProcess | undefined
	const root = await stylesProject(context, () => stopChild(child))
	const file = join(root, globalStylesheetSnapshotFile)
	await put(root, globalStylesheetSnapshotFile, '.stale {}\n')

	const result = await meeko(root, ['styles', '.'])
	assert.equal(result.code, 0, result.stderr)
	assert.equal(result.stderr, '')
	assert.equal(result.stdout.trim(), file)
	const contents = await readFile(file, 'utf8')
	assert.match(contents, /^\/\* Generated by meeko dev from app\/styles\/main\.css/)
	assert.match(contents, /\.token-rule \{/, 'the imported file is inlined')
	assert.match(contents, /\.app-rule \{/)
	assert.match(contents, /\.injected-by-plugin \{/, 'the Vite plugin of a module applied')
	assert.doesNotMatch(contents, /@import|\.stale/)
	// Nothing else: no entries, declarations or caches, and no atomic-write leftovers.
	assert.deepEqual(await readdir(join(root, '.meeko')), ['styles'])
	assert.deepEqual(await readdir(join(root, '.meeko', 'styles')), ['main.css'])

	// The same stylesheet, byte for byte, as the one `meeko dev` keeps for the same project.
	await rm(file)
	const port = await freePort()
	let logs = ''
	child = spawn(process.execPath, [cli, 'dev', root], {
		cwd: root,
		env: { ...process.env, PORT: String(port), MEEKO_HMR_PORT: String(await freePort()), MEEKO_EDITOR_BRIDGE: '0', PORTLESS: '0' },
		stdio: ['ignore', 'pipe', 'pipe'],
		windowsHide: true,
	})
	child.stdout?.on('data', (chunk: Buffer) => (logs += chunk.toString()))
	child.stderr?.on('data', (chunk: Buffer) => (logs += chunk.toString()))
	await until(
		() => existsSync(file) || child!.exitCode !== null,
		() => `meeko dev wrote no snapshot: ${logs}`,
		60_000,
	)
	await until(
		async () => (await readFile(file, 'utf8')).includes('.injected-by-plugin'),
		() => `meeko dev snapshot: ${logs}`,
	)
	assert.equal(await readFile(file, 'utf8'), contents)
})

test('meeko styles writes nothing without stylesheets and removes a stale snapshot', { timeout: 120_000 }, async (context) => {
	const root = await stylesProject(context)
	await rm(join(root, 'app/styles'), { recursive: true })
	await put(root, globalStylesheetSnapshotFile, '.stale {}\n')
	const result = await meeko(root, ['styles', '.'])
	assert.equal(result.code, 0, result.stderr)
	assert.equal(result.stderr, '')
	assert.match(result.stdout, /sin hojas de estilos/)
	assert.equal(existsSync(join(root, globalStylesheetSnapshotFile)), false)
	assert.equal(existsSync(join(root, '.meeko', 'generated')), false)
})

test('meeko styles fails and keeps the previous snapshot when the stylesheets do not compile', { timeout: 120_000 }, async (context) => {
	const root = await stylesProject(context)
	assert.equal((await meeko(root, ['styles', '.'])).code, 0)
	const good = await readFile(join(root, globalStylesheetSnapshotFile), 'utf8')
	await put(root, 'app/styles/broken.flag', '')
	const result = await meeko(root, ['styles', '.'])
	assert.equal(result.code, 1)
	assert.match(result.stderr, /conserva la versión anterior[^]*injected failure/)
	assert.equal(await readFile(join(root, globalStylesheetSnapshotFile), 'utf8'), good)
	// Without an earlier snapshot, it says there is none.
	await rm(join(root, globalStylesheetSnapshotFile))
	const first = await meeko(root, ['styles', '.'])
	assert.equal(first.code, 1)
	assert.match(first.stderr, /no se escribió[^]*injected failure/)
	assert.equal(existsSync(join(root, globalStylesheetSnapshotFile)), false)
})

test('meeko check also writes the stylesheet, and only warns when it does not compile', { timeout: 180_000 }, async (context) => {
	const root = await stylesProject(context)
	const file = join(root, globalStylesheetSnapshotFile)
	const checked = await meeko(root, ['check', '.'])
	assert.equal(checked.code, 0, checked.stderr + checked.stdout)
	assert.match(checked.stdout, /: OK/)
	assert.match(await readFile(file, 'utf8'), /\.injected-by-plugin \{/)

	// A stylesheet that stops compiling is a warning: check passed before and still passes.
	await put(root, 'app/styles/broken.flag', '')
	const warned = await meeko(root, ['check', '.'])
	assert.equal(warned.code, 0, warned.stderr + warned.stdout)
	assert.match(warned.stdout, /: OK/)
	assert.match(warned.stderr, /\[meeko\] \.meeko\/styles\/main\.css conserva la versión anterior[^]*injected failure/)
	assert.match(await readFile(file, 'utf8'), /\.injected-by-plugin \{/)
})
