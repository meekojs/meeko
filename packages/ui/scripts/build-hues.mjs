// Genera, con los valores de @radix-ui/colors, las escalas crudas de src/app/styles/hues.css (entrada opcional
// `@meekojs/ui/hues`) y el gris alfa de palette.css, que la hoja principal da siempre porque lo usa `glass`.
// Ambos resultados se versionan. Uso: pnpm -F @meekojs/ui run generate:hues
import * as radix from '@radix-ui/colors'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { hueNames } from './build-appearance.mjs'

const styles = new URL('../src/app/styles/', import.meta.url)
const steps = Array.from({ length: 12 }, (_, index) => index + 1)

/**
 * El texto sobre el paso 9. Radix aclara tanto el sólido de estas escalas que pide texto oscuro: el paso 12
 * claro del gris con que Radix las empareja. El resto lleva texto blanco.
 */
const darkText = { sky: 'slate', mint: 'sage', lime: 'olive', yellow: 'sand', amber: 'sand' }
const contrast = (hue) => (darkText[hue] ? radix[darkText[hue]][`${darkText[hue]}12`] : '#ffffff')

/** Los doce pasos de una escala de Radix, en el orden de sus claves. */
function scale(name, key = name) {
	const values = radix[name]
	if (!values) throw new Error(`@radix-ui/colors no tiene la escala ${name}`)
	return steps.map((step) => {
		const value = values[`${key}${step}`]
		if (!/^#[0-9a-f]{6}(?:[0-9a-f]{2})?$/.test(value ?? '')) throw new Error(`${name}: paso ${step} inesperado: ${value}`)
		return value
	})
}

const declarations = (hue, values) => [...values.map((value, index) => `\t--color-${hue}-${index + 1}: ${value};`), `\t--color-${hue}-contrast: ${contrast(hue)};`].join('\n')

const hues = `/*
 * Optional entry of @meekojs/ui: the raw hues of Radix Colors and the classes of their combinations, which the
 * main entry leaves out. After the main entry:
 *
 *   @import 'tailwindcss';
 *   @import '@meekojs/ui';
 *   @import '@meekojs/ui/hues';
 *
 * Generated by scripts/build-hues.mjs from @radix-ui/colors: do not edit by hand. Each hue has --color-<hue>-1…12
 * and --color-<hue>-contrast, the text on step 9. The alpha gray (gray-a1…a12) is in the main entry.
 */
@source '../theme/base/hues.ts';
@source '../../../dist/app/theme/base/hues.js';

@theme {
${hueNames.map((hue) => declarations(hue, scale(hue))).join('\n\n')}
}

:root[data-theme='dark'] {
${hueNames.map((hue) => declarations(hue, scale(`${hue}Dark`, hue))).join('\n\n')}
}
`
writeFileSync(new URL('hues.css', styles), hues)

// The alpha gray goes in palette.css, between its markers, in the light block and in the dark one.
const palette = new URL('palette.css', styles)
let css = readFileSync(palette, 'utf8')
for (const [marker, name] of [
	['grayA', 'grayA'],
	['grayDarkA', 'grayDarkA'],
]) {
	const region = new RegExp(`(/\\* ${marker}: generated by scripts/build-hues\\.mjs \\*/\\n)[^]*?(\\t/\\* end of ${marker} \\*/)`)
	if (!region.test(css)) throw new Error(`palette.css no tiene las marcas de ${marker}`)
	const values = scale(name, 'grayA')
		.map((value, index) => `\t--ui-color-gray-a${index + 1}: ${value};\n`)
		.join('')
	css = css.replace(region, (_, start, end) => `${start}${values}${end}`)
}
writeFileSync(palette, css)
console.log(`Generados ${fileURLToPath(new URL('hues.css', styles))} y el gris alfa de palette.css`)
