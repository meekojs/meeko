const aliases = { neutral: 'surface', secondary: 'surface', accent: 'primary', error: 'danger' }
const existing = ['primary', 'surface', 'info', 'success', 'warning', 'danger', 'cyan', 'orange', 'pink']
const lightSteps = [50, [50, 100], 100, 200, 300, 400, 500, 600, 800, 900, [800, 900], 950]
const darkSteps = [950, [950, 900], 900, 800, 700, 600, 500, 400, 300, 200, [300, 200], 100]

/** Genera utilidades locales y escalas físicas a partir del catálogo de colores. */
export function appearanceStyles(colors, tailwindColors) {
	const shade = (palette, level) => {
		const value = tailwindColors.get(`--color-${palette}-${level}`)
		if (!value) throw new Error(`Falta el color ${palette}-${level} en la paleta de Tailwind`)
		return value
	}
	const stepColor = (palette, level) => (Array.isArray(level) ? `color-mix(in oklab, ${shade(palette, level[0])}, ${shade(palette, level[1])})` : shade(palette, level))

	const light = []
	const dark = []
	const utilities = []

	for (const [color, utility] of Object.entries(colors)) {
		const palette = aliases[color] ?? color
		const token = (step) => `--ui-color-${palette}-${step}`
		const physical = !existing.includes(palette)
		const variables = lightSteps.map((lightStep, index) => {
			const step = index + 1
			if (physical) {
				light.push(`\t\t${token(step)}: ${stepColor(palette, lightStep)};`)
				dark.push(`\t\t${token(step)}: ${stepColor(palette, darkSteps[index])};`)
			}
			return `\t\t--ui-${step}: var(${token(step)});`
		})

		if (physical) {
			for (const step of ['contrast', 'contrast-hover']) {
				light.push(`\t\t${token(step)}: #fff;`)
				dark.push(`\t\t${token(step)}: #000;`)
			}
		}

		variables.push(`\t\t--ui-contrast: var(${token('contrast')});`, `\t\t--ui-contrast-hover: var(${token('contrast-hover')});`, `\t\t--ui-gradient-end: color-mix(in srgb, var(${token(9)}) 80%, rgb(from var(${token('contrast')}) calc(255 - r) calc(255 - g) calc(255 - b)));`)
		utilities.push(`\t.${utility} {\n${variables.join('\n')}\n\t}`)
	}

	return `/* Generated by scripts/build-styles.mjs from the appearance catalog. */
@layer ui.theme {
	:root {
${light.join('\n')}
	}

	:root[data-theme='dark'] {
${dark.join('\n')}
	}
}

@layer ui.utilities {
${utilities.join('\n\n')}
}
`
}
