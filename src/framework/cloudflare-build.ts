import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import type { MeekoServerConfig } from "./config-type.js";

type CloudflareConfig = Extract<MeekoServerConfig, { adapter: "cloudflare" }>;

/** Workers compatibility date that Meeko's workerd conformance suite runs with. */
export const cloudflareCompatibilityDate = "2026-10-19";
/** Durable Object binding of Socket rooms, read by the generated Worker. */
export const cloudflareSocketBinding = "MEEKO_SOCKET";
/** Static assets directory inside the Cloudflare output. */
export const cloudflareAssetsDirectory = "assets";
/** Prerendered pages live with the assets, under a prefix the Worker never serves publicly. */
export const cloudflarePrerenderDirectory = "assets/_meeko/prerender";

const ownedFields = ["main", "assets", "no_bundle", "find_additional_modules"] as const;

function workerName(value: string | undefined): string {
  const name = (value ?? "").toLowerCase().replace(/^@[^/]+\//, "").replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 63).replace(/-+$/, "");
  return name || "meeko-app";
}

async function packageName(root: string): Promise<string | undefined> {
  try { return (JSON.parse(await readFile(join(root, "package.json"), "utf8")) as { name?: unknown }).name as string | undefined; }
  catch { return undefined; }
}

function list(value: unknown, label: string): unknown[] {
  if (value === undefined) return [];
  if (!Array.isArray(value)) throw new TypeError(`server.wrangler.${label} must be an array`);
  return value;
}

/**
 * The generated `wrangler.jsonc`: the bundled Worker, static assets read only
 * through the Worker, `nodejs_als`, and the Socket room Durable Object with its
 * SQLite migration, combined with the application's extra fields.
 */
export async function wranglerConfig(root: string, config: CloudflareConfig | undefined): Promise<Record<string, unknown>> {
  const extra: Record<string, unknown> = { ...config?.wrangler ?? {} };
  for (const field of ownedFields) {
    if (field in extra) throw new TypeError(`server.wrangler.${field} is generated by Meeko and cannot be overridden`);
  }
  const className = config?.socketClassName ?? "MeekoSocketRoom";
  const flags = [...new Set(["nodejs_als", ...list(extra.compatibility_flags, "compatibility_flags").map(String)])];
  const durableObjects = (extra.durable_objects ?? {}) as { bindings?: unknown };
  if (typeof durableObjects !== "object" || durableObjects === null) throw new TypeError("server.wrangler.durable_objects must be an object");
  const bindings = list(durableObjects.bindings, "durable_objects.bindings") as Array<{ name?: unknown }>;
  if (bindings.some((binding) => binding?.name === cloudflareSocketBinding)) {
    throw new TypeError(`server.wrangler.durable_objects.bindings cannot redefine ${cloudflareSocketBinding}`);
  }
  const migrations = list(extra.migrations, "migrations") as Array<Record<string, unknown>>;
  // Durable Object migrations are append-only history; keep the room class's once.
  const declared = migrations.some((migration) => ["new_sqlite_classes", "new_classes"].some((key) =>
    Array.isArray(migration?.[key]) && (migration[key] as unknown[]).includes(className)));
  delete extra.compatibility_flags;
  delete extra.durable_objects;
  delete extra.migrations;
  return {
    name: config?.name ?? workerName(await packageName(root)),
    main: "./worker.js",
    // worker.js is already bundled; Wrangler uploads exactly what was tested,
    // without attaching the asset files next to it as extra modules.
    no_bundle: true,
    find_additional_modules: false,
    compatibility_date: config?.compatibilityDate ?? cloudflareCompatibilityDate,
    compatibility_flags: flags,
    assets: {
      directory: `./${cloudflareAssetsDirectory}`,
      binding: "ASSETS",
      // Every request reaches the Worker, which serves only manifest-listed files.
      run_worker_first: true,
      html_handling: "none",
      not_found_handling: "none",
    },
    ...extra,
    durable_objects: { ...durableObjects, bindings: [{ name: cloudflareSocketBinding, class_name: className }, ...bindings] },
    migrations: declared ? migrations : [{ tag: "meeko-socket-v1", new_sqlite_classes: [className] }, ...migrations],
  };
}

/** Serializes the generated configuration with a provenance comment. */
export function wranglerSource(config: Record<string, unknown>): string {
  return `// Generated by meeko build --adapter cloudflare; configure it in meeko.config.ts (server.wrangler).\n${JSON.stringify(config, null, 2)}\n`;
}

/** Locates Wrangler's CLI from the project, then from Meeko's own installation. */
export function resolveWrangler(root: string): string | undefined {
  for (const base of [join(resolve(root), "package.json"), import.meta.url]) {
    try {
      const manifest = createRequire(base).resolve("wrangler/package.json");
      const bin = join(dirname(manifest), "bin", "wrangler.js");
      if (existsSync(bin)) return bin;
    } catch { /* Not installed from this location. */ }
  }
  return undefined;
}
